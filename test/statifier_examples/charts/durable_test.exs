  # `terminate: true`, exactly as the editor page compiles it: it is what
  # gives the emission a top-level `<final>` per root outcome, and so what
  # lets an execution reach `:done` and its record `:completed`. It is part of the
  # generated bytes and therefore of the content hash, so `recompile!/1`
  # below has to pass it too or a resume would be refused on identity.
  defp compile!(document, declare \\ []) do
    {:ok, compiled} =
      Compiler.compile(document, Charts.palette(),
        known_invoke_types: Charts.invoke_types(),
        declare: declare,
        terminate: true
      )

    compiled
  end

  defp signup do
    {:ok, fixture} = Charts.fixture("signup_wizard")

    {compile!(fixture.document, fixture.declare), fixture.document}
  end

  # The wizard compiled the way `signup/0` compiled it, for the resume side
  # of a test. The declarations are part of the generated bytes, so a resume
  # that dropped them would be refused on chart identity rather than
  # reloading the execution.
  defp recompile!(document) do
    {:ok, fixture} = Charts.fixture("signup_wizard")

    compile!(document, fixture.declare)
  end

  # A one-block document, built here rather than added to `priv/fixtures`,
  # because what it is for is reaching `myapp:provision` in two steps
  # rather than by driving the whole wizard: the tests below it are about
  # the durable driver's write, not about the wizard's shape.
  #
  # The shipped wizard used to be unable to reach provisioning at all - its
  # plan branch guarded on `signup.plan` and `signup.seats` with nothing
  # declaring `signup`, so both guards raised `error.execution` and every
  # execution took the `otherwise` arm and abandoned. It provisions now, and
  # "the wizard shipped in `priv/fixtures` provisions" below is what says
  # so; this stand-in stays because it is the smaller fixture for the three
  # driver tests, not because the wizard cannot.
  defp provisioning do
    {:ok, document} =
      Decode.decode("""
      {
        "schema_version": 1,
        "id": "bdoc_provision_only",
        "revision": 1,
        "metadata": {"name": "Provision only", "domain": "signup"},
        "root": {
          "type": "core.sequence",
          "id": "blk_po_root",
          "type_version": 1,
          "slots": {
            "body": [
              {
                "type": "myapp.provision",
                "id": "blk_po_provision",
                "type_version": 1,
                "config": {"invoke_type": "myapp:provision", "label": "Create the workspace"}
              }
            ]
          }
        }
      }
      """)

    {compile!(document), document}
  end

  defp store! do
    {:ok, store} = Storage.new(StatifierExamples.Persistence, [])

    store
  end

  defp record!(execution_id) do
    {:ok, record} = Storage.fetch_execution(store!(), execution_id)

    record
  end

  defp kinds(run), do: run |> Execution.entries() |> Enum.map(& &1.kind)

  defp details(run), do: run |> Execution.entries() |> Enum.map(& &1.detail)

  defp accounts(execution_id) do
    email = Accounts.email_for(execution_id)

    Repo.one!(from(u in User, where: u.email == ^email, select: count()))
  end

